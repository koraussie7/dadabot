/**
 * octokit.ts — GitHub PR bridge.
 *
 * busabase's Inbox is local. Dadabot runs as a desktop app + cloud hybrid, so
 * we optionally mirror every "open" ChangeRequest as a draft PR on a
 * configured GitHub repo. This:
 *
 *   - provides off-device audit + backup
 *   - lets non-technical reviewers approve from their phone via the GitHub mobile app
 *   - leverages GitHub's existing code-review + diff rendering
 *
 * Implementation uses @octokit/rest. No network calls in this file's exported
 * helpers — they construct the Octokit call so it can be retried / mocked.
 */

import type { ChangeRequest } from "./change-request.ts";

export interface PrDraft {
  owner: string;
  repo: string;
  title: string;
  body: string;
  head: string;        // branch name (e.g. `dadabot/cr-<uuid12>`)
  base: string;        // default branch (e.g. "main")
  labels: string[];
}

export interface PrMirror {
  url: string;
  number: number;
  headSha: string;
}

/**
 * Build the PR title + body from a ChangeRequest.
 * Pure function — easy to snapshot-test, no I/O.
 */
export function buildPrDraft(cr: ChangeRequest, baseBranch: string): PrDraft {
  const head = `dadabot/cr-${cr.id.slice(0, 8)}`;
  const fp = cr.id.slice(0, 12);
  const labels = [
    "dadabot",
    "human-in-the-loop",
    `confidence:${cr.confidence.toFixed(2)}`,
  ];
  if (cr.policy.permission === "autoMerge") labels.push("auto-merged");

  const fileSummary = cr.files
    .map(
      (f) =>
        `- \`${f.path}\` (${f.operation}, +${f.linesAdded}/-${f.linesRemoved})`,
    )
    .join("\n");

  const body = [
    `## ${cr.title}`,
    "",
    `**Agent:** \`${cr.agent.name}\` v${cr.agent.version}`,
    `**Model:** ${cr.agent.modelProvider}/${cr.agent.modelId}`,
    `**Category:** \`${cr.category}\``,
    `**Confidence:** ${cr.confidence.toFixed(2)}`,
    `**Permission:** \`${cr.policy.permission}\``,
    `**Reversible:** ${cr.reversible ? "yes" : "no"}`,
    `**Fingerprint:** \`${fp}\``,
    "",
    "### Rationale",
    cr.rationale,
    "",
    "### Policy decision",
    cr.policy.reason,
    "",
    "### Files",
    fileSummary,
    "",
    cr.dryRunPreview
      ? ["### Dry-run preview", "```diff", cr.dryRunPreview, "```", ""].join("\n")
      : "",
    "---",
    "🤖 Generated by [DadaBot](https://dadabot.dev) — `busabase-adapter`",
    "Approve by merging, reject by closing.",
  ]
    .filter(Boolean)
    .join("\n");

  return {
    owner: "", // filled by caller (config)
    repo: "",
    title: `[DadaBot ${cr.policy.permission}] ${cr.title}`,
    body,
    head,
    base: baseBranch,
    labels,
  };
}

/**
 * Construct the GitHub Actions one-liner that an Octokit caller can run.
 * Returned as a function, so tests can mock the API client.
 */
export interface OctokitLike {
  pulls: {
    create: (params: Record<string, unknown>) => Promise<{ data: { html_url: string; number: number; head: { sha: string } } }>;
  };
}

export async function openPr(
  octokit: OctokitLike,
  draft: PrDraft & { owner: string; repo: string },
): Promise<PrMirror> {
  const { data } = await octokit.pulls.create({
    owner: draft.owner,
    repo: draft.repo,
    title: draft.title,
    body: draft.body,
    head: draft.head,
    base: draft.base,
    draft: true,
  });
  return {
    url: data.html_url,
    number: data.number,
    headSha: data.head.sha,
  };
}
